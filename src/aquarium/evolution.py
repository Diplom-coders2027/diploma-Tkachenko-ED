"""Стадии эволюции существ.

Существа стартуют клеткой. Каждая победа в раунде (1 место) переводит
победителя на следующую стадию. После последней (кракен) цикл начинается
заново с клетки.

Каждая стадия даёт плюсы и минусы (множители относительно рыбки = 1.0):
  speed   — макс. скорость (быстрее = выше цена движения, это уже учтено)
  dmg     — урон укуса
  cap     — запас энергии
  upkeep  — базовая трата энергии в тик (чем крупнее, тем дороже жить)
"""
import numpy as np

# (код, название, скорость, урон, запас энергии, содержание)
STAGES = [
    ("cell", "клетка", 1.10, 0.80, 0.85, 0.80),
    ("fish", "рыба", 1.00, 1.00, 1.00, 1.00),
    ("hedgehog", "рыба-ёж", 0.95, 1.10, 1.15, 1.05),
    ("swordfish", "рыба-меч", 1.20, 1.20, 0.95, 1.10),
    ("narwhal", "нарвал", 1.05, 1.30, 1.05, 1.15),
    ("shark", "акула", 1.15, 1.35, 1.10, 1.20),
    ("kraken", "кракен", 0.90, 1.50, 1.30, 1.35),
    ("dolphin", "дельфин", 1.25, 1.15, 1.05, 1.10),
    ("orca", "косатка", 1.15, 1.45, 1.20, 1.25),
    ("eel", "электрический угорь", 1.30, 1.10, 0.95, 1.00),
    ("tuna", "тунец", 1.35, 1.25, 1.00, 1.15),
    ("anglerfish", "рыба-фонарь", 0.80, 1.40, 1.15, 1.20),
    ("serpent", "морской змей", 1.10, 1.50, 1.25, 1.30),
    ("giant_squid", "гигантский кальмар", 1.00, 1.55, 1.35, 1.40),
    ("leviathan", "левиафан", 0.75, 1.60, 1.50, 1.50),
    ("megalodon", "мегалодон", 1.05, 1.80, 1.35, 1.55),
    ("abyss_dragon", "дракон бездны", 1.10, 2.00, 1.60, 1.70),
]
N_STAGES = len(STAGES)

# таблица бонусов для ядер numba: строка = стадия, столбцы см. выше
STAGE_BONUS = np.array([row[2:] for row in STAGES], dtype=np.float64)
B_SPEED, B_DMG, B_CAP, B_UPKEEP = 0, 1, 2, 3


def next_stage(stage):
    """Следующая стадия; после кракена — снова клетка."""
    return (int(stage) + 1) % N_STAGES


def stage_name(stage):
    return STAGES[int(stage) % N_STAGES][1]


def stage_effect_text(stage):
    """Короткая строка с бонусами и штрафами для баннера."""
    _, _, sp, dm, cp, up = STAGES[int(stage) % N_STAGES]
    def pct(v):
        d = round((v - 1.0) * 100)
        return "%+d%%" % d
    return "скор. %s, урон %s, энергия %s, расход %s" % (
        pct(sp), pct(dm), pct(cp), pct(up))
